const SOUND_CLASH = [['c', 'k'], ['a', 'o'], ['a', 'u'], ['o', 'u']];   // never put these together (they sound alike)
function clash(a, b) { return SOUND_CLASH.some(([x, y]) => (a === x && b === y) || (a === y && b === x)); }
function wordDistractors(w, pool) {
  const all = Array.from(new Set([].concat(...Object.values(RD.words)))).filter(x => x !== w && x.toLowerCase() !== w.toLowerCase());
  const score = x => Math.abs(x.length - w.length) * 2 + (x[0].toLowerCase() === w[0].toLowerCase() ? -1.5 : 0) + (pool.includes(x) ? -3 : 0) + Math.random() * 1.2;
  return all.sort((a, b) => score(a) - score(b)).slice(0, 2);
}
function buildQuestions(n) {
  const L = RL[n]; const qs = [];
  let pool;
  if (L.type === 'words') pool = RD.words[String(n)];
  else if (L.type === 'sounds') pool = RD.sounds[String(n)];
  else pool = RD.math[String(n)];
  let bag = [];
  while (qs.length < QUESTIONS) {
    if (!bag.length) bag = shuffle(pool);
    let item = bag.pop();
    const prev = qs[qs.length - 1];
    const same = x => prev && (prev.id === JSON.stringify(x) || (L.type === 'math' && prev.ans === x.ans));   // v12: no back-to-back repeats (math: not even the same answer)
    for (let tries = 0; same(item) && bag.length && tries < bag.length; tries++) { bag.unshift(item); item = bag.pop(); }
    let q;
    if (L.type === 'words') {
      q = { id: JSON.stringify(item), ans: item, opts: [item, ...wordDistractors(item, pool)], k: wkey(item) };
    } else if (L.type === 'sounds') {
      const others = shuffle([...pool, ...'mstapnbdfg'.split('')].filter(x => x !== item && !clash(x, item)));
      const d = Array.from(new Set(others)).slice(0, 2);
      q = { id: JSON.stringify(item), ans: item, opts: [item, ...d], k: 'rp_' + item, show: x => x.toUpperCase() + x };
    } else {
      const a = item.ans; const cands = shuffle([a + 1, a - 1, a + 2, a - 2, a + 3].filter(x => x >= 0 && x <= 20 && x !== a));
      q = { id: JSON.stringify(item), ans: a, opts: [a, cands[0], cands[1]], k: item.k, math: item };
    }
    q.opts = shuffle(q.opts); q.lane = q.opts.indexOf(q.ans) - 1;
    qs.push(q);
  }
  return qs;
}

